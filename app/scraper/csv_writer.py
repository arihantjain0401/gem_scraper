"""CSV output, preserved verbatim from the original scraper."""

import csv

from app.scraper.mapping import CSV_COLUMNS


def write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
